# ---- job folders ------------------------------------------------------------------

def test_stem_strips_only_known_suffixes():
    assert part.stem("ball_joint.T2.gcode") == "ball_joint"
    assert part.stem(r"D:\x\ball_joint.3mf") == "ball_joint"
    assert part.stem("a.T2.printer.ini") == "a"
    assert part.stem("a.blender_layer1.png") == "a" and part.stem("a_below.png") == "a"
    assert part.stem("v1.2_bracket.scad") == "v1.2_bracket"
    assert part.stem("light remote holder.scad") == "light remote holder"


def test_job_dir_is_named_after_the_part(tmp_path):
    root = tmp_path / "parts"
    d = part.job_dir(str(tmp_path / "foo.T2.gcode"), root=str(root))
    assert d == str(root / "foo") and os.path.isdir(d)
    # a source already in its own folder stays there
    own = tmp_path / "bar"
    own.mkdir()
    src = own / "bar.scad"
    src.write_text("cube(1);")
    assert part.job_dir(str(src), root=str(root)) == str(own)
    # an explicit folder wins
    assert part.job_dir("anything.stl", job=str(tmp_path / "custom"), root=str(root)) == str(tmp_path / "custom")
    assert part.job_path(str(src), ".stl", root=str(root)) == str(own / "bar.stl")


# ---- estimate and fit --------------------------------------------------------------

def test_parse_time():
    assert part.parse_time("1h 51m 30s") == 6690
    assert part.parse_time("59m 4s") == 3544
    assert part.parse_time("1d 2h") == 93600
    assert part.parse_time("nonsense") is None


def test_estimate_reads_the_trailer(tmp_path):
    g = tmp_path / "widget.T2.gcode"
    g.write_text(TRAILER, newline="\n")
    est = part.estimate(str(g), job=str(tmp_path / "widget"))
    assert est["time_s"] == 6690 and est["time_hm"] == "1:51"
    assert est["filament_g_total"] == 12.15 and est["filament_cm3"] == 9.8 and est["layers"] == 2
    assert est["tool"] == 2 and est["extruding_moves"] == 3 and est["problems"] == []
    assert est["extents"]["x"] == (10.0, 30.0)
    assert os.path.exists(est["written"]) and json.load(open(est["written"]))["time_s"] == 6690
    assert part.describe(est).startswith("1:51, 12.2 g, 2 layers, 20 x 20 x 1 mm on the bed")


def _info(sx, sy, sz, manifold="yes", parts=1):
    return {"size_x": sx, "size_y": sy, "size_z": sz, "manifold": manifold, "number_of_parts": parts,
            "volume": sx * sy * sz, "number_of_facets": 12}


def test_fit_against_the_bed():
    ok, warn, det = part.fit("x.stl", mesh_info=_info(30, 30, 30))
    assert ok == [] and warn == [] and det["bed"] == [300.0, 200.0, 300.0]
    bad, _, _ = part.fit("x.stl", mesh_info=_info(310, 30, 30))
    assert any("does not fit" in p for p in bad)
    bad, _, _ = part.fit("x.stl", mesh_info=_info(30, 30, 301))
    assert any("height" in p for p in bad)
    bad, _, _ = part.fit("x.stl", mesh_info=_info(30, 30, 30, manifold="no"))
    assert any("manifold" in p for p in bad)
    _, warn, _ = part.fit("x.stl", mesh_info=_info(5, 30, 30))
    assert any("adhesion" in w for w in warn) and any("tall" in w for w in warn)
    _, warn, _ = part.fit("x.stl", mesh_info=_info(30, 30, 30, parts=3))
    assert any("3 separate parts" in w for w in warn)


# ---- Blender helpers --------------------------------------------------------------

def _paths():
    # three layers, two beads each, somewhere on the bed
    return [[[200 + i, 100, z], [210 + i, 100, z]] for z in (0.35, 0.55, 0.75) for i in (0, 5)]


def test_layers_subsample_first_layer_and_recentre():
    p = _paths()
    assert part.layers_of(p) == [0.35, 0.55, 0.75]
    assert len(part.first_layer(p)) == 2
    sub = part.subsample(p, 2)
    assert part.layers_of(sub) == [0.35, 0.75]
    assert part.subsample(p, 1) == p
    c, extent = part.recentre(p)
    xs = [pt[0] for q in c for pt in q]
    assert abs(max(xs) + min(xs)) < 1e-9 and extent == (15, 0)


# ---- the real tools --------------------------------------------------------------

@needs_openscad
@needs_prusa
def test_render_and_preview_a_cube(tmp_path):
    scad = tmp_path / "cube.scad"
    scad.write_text(CUBE)
    job = str(tmp_path / "cube")
    stl, d, warnings = part.render(str(scad), job=job)
    assert stl == os.path.join(job, "cube.stl") and d["manifold"] == "yes"
    assert abs(d["size_x"] - 20) < 1e-3 and abs(d["size_z"] - 10) < 1e-3
    above, below = part.preview(str(scad), job=job, size=(200, 150))
    assert os.path.getsize(above) > 500 and os.path.getsize(below) > 500
    with pytest.raises(part.PartError):
        part.render(str(scad), defines=["nonsense"], job=job)
    bad = tmp_path / "bad.scad"
    bad.write_text("cube([1,1,1]); foo(\n")
    with pytest.raises(part.PartError):
        part.render(str(bad), job=job)


@needs_openscad
@needs_prusa
def test_slice_a_scad_with_the_profiles(tmp_path):
    scad = tmp_path / "cube.scad"
    scad.write_text(CUBE)
    job = str(tmp_path / "cube")
    out = agent.slice_model(str(scad), [], 2, job=job)
    assert out == os.path.join(job, "cube.T2.gcode")
    est = part.estimate(out, job=job)
    assert est["problems"] == [] and est["layers"] > 20 and est["filament_g_total"] > 0
    assert os.path.exists(os.path.join(job, "cube.T2.printer.ini"))


@needs_blender
def test_render_blender_a_small_square(tmp_path):
    g = tmp_path / "sq.T2.gcode"
    lines = ["T-1", "G10 P2 S220 R220", "T2", "M116 P2", "G90", "M82"]
    e = 0.0
    for z in (0.35, 0.55, 0.75):
        lines.append(f"G1 Z{z} F600")
        lines.append(";LAYER_CHANGE")
        lines.append("G0 X100 Y100")
        for x, y in ((110, 100), (110, 110), (100, 110), (100, 100)):
            e += 0.5
            lines.append(f"G1 X{x} Y{y} E{e:.3f} F1200")
    lines += ["T-1", "G10 P2 S0 R0"]
    g.write_text("\n".join(lines) + "\n", newline="\n")
    job = str(tmp_path / "sq")
    r = part.render_blender(str(g), size=(160, 90), samples=2, job=job, log=lambda m: None)
    assert r["layers"] == 3 and r["beads"] == 3
    assert os.path.getsize(r["build"]) > 500 and os.path.getsize(r["layer1"]) > 500
    assert r["build"] == os.path.join(job, "sq.blender.png")
