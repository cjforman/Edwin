class FakeDuetState:
    def __init__(self):
        self.files = {}
        self.status = "idle"
        self.homed = True
        self.session_ok = False
        self.writing = None
        self.replies = []
        self.job_file = None
        self.job_pos = 0
        self.lock = threading.Lock()
        # fault injection
        self.reset_next = 0          # close the next N connections without answering
        self.expire_after = None     # after N requests, require a new rr_connect
        self.fail_after_apply = []   # (gcode substring, times): apply then close without a reply
        self.request_count = 0
        self.gcode_log = []
        self.drop_upload_after = None  # drop the connection after reading N body bytes (leaving a partial file)
        self.upload_headers = []


class Handler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.0"
    state = None  # type: FakeDuetState

    def log_message(self, *a):
        pass

    def _drop(self):
        try:
            self.connection.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass
        self.connection.close()

    def _json(self, obj, code=200):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        s = self.state
        u = urllib.parse.urlsplit(self.path)
        q = dict(urllib.parse.parse_qsl(u.query, keep_blank_values=True))
        with s.lock:
            s.request_count += 1
            if s.reset_next > 0:
                s.reset_next -= 1
                return self._drop()
            if u.path == "/rr_connect":
                s.session_ok = True
                return self._json({"err": 0, "sessionTimeout": 8000, "sessionKey": 0})
            if u.path == "/rr_disconnect":
                s.session_ok = False
                return self._json({"err": 0})
            if s.expire_after is not None and s.request_count > s.expire_after:
                s.expire_after = None
                s.session_ok = False
            if not s.session_ok:
                return self._json({"err": 1}, 401)
            if u.path == "/rr_model":
                return self._json({"key": q.get("key"), "flags": q.get("flags", ""), "result": self.model(q.get("key", ""))})
            if u.path == "/rr_gcode":
                return self.gcode(q.get("gcode", ""))
            if u.path == "/rr_reply":
                r = "\n".join(s.replies)
                s.replies = []
                return self._json(r) if False else self._text(r)
            if u.path == "/rr_fileinfo":
                name = q["name"]
                if name in s.files:
                    return self._json({"err": 0, "fileName": name, "size": len(s.files[name])})
                return self._json({"err": 1})
            if u.path == "/rr_download":
                data = s.files.get(q["name"])
                if data is None:
                    self.send_response(404)
                    self.end_headers()
                    return
                self.send_response(200)
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)
                return
            if u.path == "/rr_delete":
                ok = s.files.pop(q["name"], None) is not None
                return self._json({"err": 0 if ok else 1})
            if u.path == "/rr_filelist":
                d = q["dir"].rstrip("/") + "/"
                files = [{"type": "f", "name": n[len(d):], "size": len(b)} for n, b in s.files.items()
                         if n.startswith(d) and "/" not in n[len(d):]]
                return self._json({"dir": q["dir"], "first": 0, "files": files, "next": 0})
            self.send_response(404)
            self.end_headers()

    def do_POST(self):
        s = self.state
        u = urllib.parse.urlsplit(self.path)
        q = dict(urllib.parse.parse_qsl(u.query, keep_blank_values=True))
        with s.lock:
            s.request_count += 1
            if s.reset_next > 0:
                s.reset_next -= 1
                return self._drop()
            if not s.session_ok:
                return self._json({"err": 1}, 401)
            if u.path != "/rr_upload":
                self.send_response(404)
                self.end_headers()
                return
            n = int(self.headers["Content-Length"])
            s.upload_headers.append({k.lower(): v for k, v in self.headers.items()})
            if s.drop_upload_after is not None:
                k, s.drop_upload_after = s.drop_upload_after, None
                s.files[q["name"]] = self.rfile.read(min(k, n))
                return self._drop()
            data = self.rfile.read(n)
            if format(zlib.crc32(data) & 0xFFFFFFFF, "08x") != q.get("crc32"):
                return self._json({"err": 1})
            s.files[q["name"]] = data
            return self._json({"err": 0})

    def _text(self, text):
        body = text.encode()
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def model(self, key):
        s = self.state
        if key == "state.status":
            return s.status
        if key == "state":
            return {"status": s.status, "currentTool": -1, "upTime": 100}
        if key == "move.axes":
            return [{"letter": a, "homed": s.homed, "userPosition": 0.35 if a == "Z" else 100.0} for a in "XYZ"]
        if key == "tools":
            return [{"number": 0, "name": "cam", "heaters": [], "active": [], "standby": []},
                    {"number": 2, "name": "T2", "heaters": [2], "active": [0], "standby": [0]}]
        if key == "job":
            if s.job_file:
                size = len(s.files.get(s.job_file, b""))
                return {"file": {"fileName": s.job_file, "size": size, "numLayers": 10}, "filePosition": s.job_pos,
                        "layer": 1 + s.job_pos * 10 // max(size, 1), "duration": 12, "timesLeft": {"file": 100},
                        "lastFileName": None}
            return {"file": None, "filePosition": 0, "layer": None, "duration": None, "timesLeft": {},
                    "lastFileName": "0:/gcodes/done.gcode", "lastFileAborted": False, "lastFileCancelled": False}
        return None

    def gcode(self, code):
        s = self.state
        s.gcode_log.append(code)
        lines = code.split("\n") if code else []
        applied = False
        for ln in lines:
            if s.writing is not None:
                if ln.strip() == "M29":
                    s.writing = None
                    s.replies.append("Done saving file.")
                else:
                    s.files[s.writing] += (ln + "\n").encode()
                applied = True
            else:
                cmd = ln.split(" ", 1)[0]
                if cmd == "M28":
                    name = ln.split('"')[1]
                    s.files[name] = b""
                    s.writing = name
                    s.replies.append(f"Writing to file: {name}")
                elif cmd == "M32":
                    name = ln.split('"')[1]
                    if name in s.files:
                        s.job_file, s.job_pos, s.status = name, 0, "processing"
                        s.replies.append(f"File {name} selected for printing")
                    else:
                        s.replies.append("Error: file not found")
                elif cmd == "M29":
                    s.replies.append("Error: not writing a file")
        for i, (sub, times) in enumerate(list(s.fail_after_apply)):
            if times > 0 and applied and sub in code:
                s.fail_after_apply[i] = (sub, times - 1)
                return self._drop()
        return self._json({"buff": 250})


