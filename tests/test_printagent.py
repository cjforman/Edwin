def test_m28_lines_and_forbidden():
    lines = duet.m28_lines("G1 X1 ; c\n\n  \nM107\t \n; only\nG1 X2")
    assert lines == ["G1 X1", "M107", "G1 X2"]
    assert duet.forbidden_in_m28(["G1", "M29", "M290 R1"]) == ["M29"]
    assert duet.m28_bytes(["A", "B"]) == b"A\nB\n"


