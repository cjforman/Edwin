def test_prepared_gcode_rewrites_profile_output(tmp_path):
    raw = "M190 S60\nG10 S210 P0\nG28\nT2\nM116\nG1 X10 Y10 E1 F1200\nG1 X20 Y20 E2\nM104 S0\nG28 X0\n"
    p = tmp_path / "raw.gcode"
    p.write_text(raw)
    out, summary = agent.prepared_gcode(str(p), 2, job=str(tmp_path / "raw"))
    assert out.endswith(".T2.gcode") and summary["extruding_moves"] == 2
    text = open(out).read()
    assert text.startswith("T-1") and "G10 P2 S210 R210" in text and "T-1 ; park" in text


def test_watch_follows_job_to_the_end(fake, sample, monkeypatch):
    d = client(fake)
    fake.files["0:/gcodes/part.gcode"] = b"G1 X1\n" * 100
    fake.homed = True
    d.start("part.gcode")
    assert fake.status == "processing"
    ticks = {"n": 0}

    def sleep(s):
        ticks["n"] += 1
        fake.job_pos = min(600, ticks["n"] * 200)
        if ticks["n"] == 2:
            fake.reset_next = 1  # a dropout mid-print
        if ticks["n"] >= 4:
            fake.status, fake.job_file = "idle", None

    final = agent.watch(d, poll=0, sleep=sleep)
    assert final == "idle"
    assert d.stats["retries"] >= 1
